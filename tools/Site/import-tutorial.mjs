import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const input = process.argv[2];
if (!input) throw new Error('Usage: node tools/Site/import-tutorial.mjs <completed tutorial directory>');
const source = path.resolve(input);
const output = path.join(root, 'site', 'assets');
const chapters = JSON.parse(await readFile(path.join(source, 'chapters.json'), 'utf8'));
const transcript = JSON.parse(await readFile(path.join(source, 'transcript.json'), 'utf8'));
const original = JSON.parse(await readFile(path.join(source, 'media-manifest.json'), 'utf8'));
const media = JSON.parse(await readFile(path.join(root, 'site', 'media.json'), 'utf8'));
if (original.videoSha256 !== media.original.sha256) throw new Error('Tutorial identity does not match the original of the bundled web video');
if (Math.abs(chapters.duration - media.durationSeconds) > .05) throw new Error('Web video does not preserve the tutorial timeline');
const tutorial = {
  title: chapters.title, duration: chapters.duration,
  chapters: chapters.chapters.map(({ id, title, start, end }) => ({ id, title, start, end })),
  cues: transcript.cues.map(({ start, end, text }) => ({ start, end, text }))
};
await mkdir(output, { recursive: true });
await writeFile(path.join(output, 'tutorial-data.mjs'), `// Generated by tools/Site/import-tutorial.mjs from the completed tutorial.\nexport const tutorial = ${JSON.stringify(tutorial)};\n`);
for (const file of ['captions.srt', 'captions.vtt', 'chapters.txt', 'chapters.json', 'transcript.json']) {
  await copyFile(path.join(source, file), path.join(output, file));
}
// Only allowlisted public media identity; never copy the private delivery/source-path inventory.
await writeFile(path.join(output, 'media-manifest.json'), JSON.stringify({
  video: media, origin: transcript.origin, caveat: transcript.caveat,
  narration: 'Synthetic Microsoft Zira Desktop / Windows System.Speech',
  lessons: 194, captionCues: tutorial.cues.length, chapters: tutorial.chapters,
  sourceManifestSha256: original.sourceSha256
}, null, 2) + '\n');
console.log(`Imported ${tutorial.chapters.length} chapters and ${tutorial.cues.length} cues.`);
